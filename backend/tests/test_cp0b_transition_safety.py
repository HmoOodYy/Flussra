"""
CP-0B integration tests — Lifecycle transition expected-state safety.

Goal: Every payroll lifecycle transition must predicate on the expected source
status at the actual write boundary.  A stale or concurrent transition request
whose status assumption no longer holds at write time must fail with 409, not
silently overwrite the current state.

Safe paths verified here:
  - All 'else-branch' transitions (Draft→Open, Open→Cancelled, InReview→Open,
    InReview→Cancelled, Approved→InReview, Approved→Cancelled, Locked→Archived)
    now use WHERE ... AND status = :old_status RETURNING (CP-0B fix).
  - Open→InReview already had WHERE status='Open' RETURNING (CP-0A era, safe).
  - Finalization (Approved→Locked) already had WHERE status='Approved' RETURNING.
  - Review writeback (InReview→Approved/Open) already had WHERE status='InReview'.

Race/stale simulation approach:
  psycopg2 threads commit a competing status change from within a monkeypatch of
  get_period_by_id, creating a deterministic race window: pre-flight read returns
  old_status, psycopg2 commits a different status, PATCH UPDATE finds 0 rows.

Dates: 2091-* — isolated year, avoids conflicts with other test modules.
Run from backend/:
    python -m pytest tests/test_cp0b_transition_safety.py -v
"""
import asyncio
import datetime
import itertools
import threading
import psycopg2
import pytest
import httpx
from sqlalchemy import text

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _auth(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}"}


# Each call returns a fresh (start, end) week.  2091-01-06 is a Monday;
# no other test module uses 2091 dates so there are no conflicts.
_WEEK_COUNTER = itertools.count(0)

def _next_dates() -> tuple[str, str]:
    """Return a unique (start, end) date pair for this test invocation."""
    n = next(_WEEK_COUNTER)
    base = datetime.date(2091, 1, 6)
    start = base + datetime.timedelta(weeks=n)
    end   = start + datetime.timedelta(days=6)
    return start.isoformat(), end.isoformat()


async def _cancel_active_periods(direct_db, branch_id: int) -> None:
    """Cancel only non-terminal active periods (Draft/Open/InReview/Approved).

    Does NOT attempt to cancel Locked/Archived — those statuses are protected
    by the payroll_status_immutable trigger and will never occupy the fresh
    unique date ranges generated by _next_dates().
    """
    await direct_db.execute(
        text(
            "UPDATE payroll.payrollperiods "
            "SET status = 'Cancelled' "
            "WHERE branchid = :bid "
            "  AND status IN ('Draft', 'Open', 'InReview', 'Approved')"
        ),
        {"bid": branch_id},
    )


async def _create_draft_period(
    client: httpx.AsyncClient,
    token: str,
    branch_id: int,
    direct_db,
) -> int:
    """Cancel active periods, allocate a fresh unique date range, create Draft."""
    await _cancel_active_periods(direct_db, branch_id)
    start, end = _next_dates()
    r = await client.post(
        "/payroll/periods",
        json={
            "branch_id":   branch_id,
            "period_type": "Week",
            "start_date":  start,
            "end_date":    end,
        },
        headers=_auth(token),
    )
    assert r.status_code == 201, f"create Draft period failed: {r.text}"
    return r.json()["payroll_period_id"]


async def _force_status(direct_db, period_id: int, new_status: str) -> None:
    """Directly set period status, bypassing API lifecycle guards."""
    await direct_db.execute(
        text(
            "UPDATE payroll.payrollperiods "
            "SET status = :s WHERE payrollperiodid = :pid"
        ),
        {"s": new_status, "pid": period_id},
    )


