@pytest.mark.asyncio
class TestFinalizationSafety:
    """
    Finalization already uses WHERE status='Approved' RETURNING (pre-CP-0B).
    Regression: attempting to finalize a non-Approved period must fail.
    """

    async def test_finalize_locked_period_fails(
        self,
        client: httpx.AsyncClient,
        auth_token: str,
        paytest_branch_id: int,
        direct_db,
    ):
        """Finalization rejects a period that is already Locked."""
        pid = await _create_draft_period(client, auth_token, paytest_branch_id, direct_db)
        await _force_status(direct_db, pid, "Locked")

        r = await client.post(
            f"/payroll/periods/{pid}/finalize",
            headers=_auth(auth_token),
        )
        assert r.status_code in (409, 422), (
            f"Finalizing a Locked period must fail, got {r.status_code}: {r.text}"
        )
        # Locked→Archived is the only allowed forward path; unique dates mean
        # this Archived period won't block future tests.

    async def test_finalize_inreview_period_fails(
        self,
        client: httpx.AsyncClient,
        auth_token: str,
        paytest_branch_id: int,
        direct_db,
    ):
        """Finalization rejects a period that is InReview (not Approved)."""
        pid = await _create_draft_period(client, auth_token, paytest_branch_id, direct_db)
        await _force_status(direct_db, pid, "InReview")

        r = await client.post(
            f"/payroll/periods/{pid}/finalize",
            headers=_auth(auth_token),
        )
        assert r.status_code in (409, 422), (
            f"Finalizing an InReview period must fail, got {r.status_code}: {r.text}"
        )

        # cleanup
        await _force_status(direct_db, pid, "Cancelled")
